async function audit(label) {
  await p.addScriptTag({ content: axe });
  const v = await p.evaluate(async () => (await axe.run(document, { runOnly: ["wcag2a", "wcag2aa", "best-practice"] })).violations.map((x) => `${x.id}: ${x.nodes.slice(0, 2).map((n) => n.target.join(" ") + " — " + (n.any[0]?.message ?? n.all[0]?.message ?? "").slice(0, 90)).join(" | ")}`));
  ok(`axe: ${label}`, v.length === 0, v.join(" || "));
}
